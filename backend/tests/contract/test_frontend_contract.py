@pytest.mark.parametrize("name", sorted(RESPONSES))
def test_response_fixture_matches_backend(name):
    path = CONTRACTS / "responses" / name
    actual = json.loads(json.dumps(RESPONSES[name](), ensure_ascii=False))
    if UPDATE:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(actual, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    assert path.exists(), f"{path} missing: run UPDATE_CONTRACTS=1 pytest tests/contract"
    assert json.loads(path.read_text(encoding="utf-8")) == actual, (
        f"{name} is stale. If the API change is deliberate: UPDATE_CONTRACTS=1 pytest "
        "tests/contract, then update the frontend adapter.")


def test_every_request_fixture_has_a_shape():
    names = {p.name for p in (CONTRACTS / "requests").glob("*.json")}
    assert names == set(REQUEST_SHAPES), (
        "contracts/requests and REQUEST_SHAPES disagree: map every new fixture to its shape")


@pytest.mark.parametrize("name", sorted(REQUEST_SHAPES))
def test_frontend_request_is_accepted(name):
    body = json.loads((CONTRACTS / "requests" / name).read_text(encoding="utf-8"))
    REQUEST_SHAPES[name].model_validate(body)  # raises ValidationError with the field path
