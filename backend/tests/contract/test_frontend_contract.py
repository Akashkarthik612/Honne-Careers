    cv = sample_cv()
    nw = cv.experience[0]
    proposed = Bullet(id="nw1", text="Reduced p95 payment-event latency by 38% with Kafka "
                      "Streams in Java on AWS", origin=Origin.AI, locked=False,
                      original_text=nw.bullets[0].text, original_origin=Origin.PROFILE,
                      tailor_state=TailorState.PROPOSED)
    kept = Bullet(id="nw2", text="Owned settlement end to end at 2M events/day with zero data "
                  "loss", origin=Origin.AI, locked=False, original_text=nw.bullets[1].text,
                  original_origin=Origin.PROFILE, tailor_state=TailorState.KEPT)
    edited = nw.bullets[2].model_copy(update={"origin": Origin.USER, "locked": True})
    nw = nw.model_copy(update={"bullets": [proposed, kept, edited]})
    return cv.model_copy(update={"experience": [nw, *cv.experience[1:]]})


